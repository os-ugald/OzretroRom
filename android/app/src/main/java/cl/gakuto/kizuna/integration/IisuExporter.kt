package cl.gakuto.kizuna.integration

import android.content.Context
import android.graphics.Bitmap
import android.graphics.BitmapFactory
import android.net.Uri
import androidx.documentfile.provider.DocumentFile
import cl.gakuto.kizuna.data.AppPreferences
import cl.gakuto.kizuna.data.GameEntity
import cl.gakuto.kizuna.util.ArtworkResolver
import org.json.JSONArray
import org.json.JSONObject
import java.io.BufferedInputStream
import java.net.HttpURLConnection
import java.net.URL
import java.util.zip.ZipEntry
import java.util.zip.ZipInputStream
import java.util.zip.ZipOutputStream

class IisuExporter(private val context: Context) {
    data class ExportResult(
        val descriptors: Int,
        val systems: Int,
        val assetManifests: Int,
        val artworkFiles: Int,
        val systemsWithoutFolder: List<String>,
    )

    data class IntegrationPackResult(val fileName: String, val launchCommand: String)

    fun exportConfigured(preferences: AppPreferences, games: List<GameEntity>): ExportResult {
        // Beta 4 Fix 1 restores the virtual bridge: iiSU receives tiny descriptors for the games
        // the user chooses to publish, whether or not the ROM is already local. The descriptor is
        // never a ROM copy. When iiSU launches it, SessionActivity either uses Oz's persistent ROM
        // or resolves/downloads the missing game on demand through the normal trusted Oz flow.
        val bridgeGames = games.distinctBy { it.id }
        var descriptorCount = 0
        var assetCount = 0
        var artworkCount = 0
        val exportedSystems = mutableSetOf<String>()
        val missing = mutableListOf<String>()

        val global = preferences.globalVirtualTreeUri
        bridgeGames.groupBy { it.systemId }.forEach { (systemId, systemGames) ->
            if (global == null) {
                missing += systemId
                return@forEach
            }
            val selectedRoot = DocumentFile.fromTreeUri(context, global)
                ?: error("Android no pudo abrir la carpeta global del puente iiSU")
            val brandRoot = selectedRoot.findFile(BRAND_FOLDER)
                ?: selectedRoot.createDirectory(BRAND_FOLDER)
                ?: error("No se pudo crear $BRAND_FOLDER")
            val platformFolder = brandRoot.findFile(systemId)
                ?: brandRoot.createDirectory(systemId)
                ?: error("No se pudo crear la carpeta $systemId")

            // Publishing is intentionally additive. A collection must never erase descriptors
            // previously published by another collection or by the local-library sync.
            systemGames.forEach { game ->
                if (writeDescriptor(platformFolder, game)) descriptorCount++
            }
            exportedSystems += systemId
        }

        preferences.iisuAssetsTreeUri?.let { assetsUri ->
            val assetsRoot = DocumentFile.fromTreeUri(context, assetsUri)
                ?: error("Android no pudo abrir la carpeta de assets de iiSU")
            val brandAssets = assetsRoot.findFile(ASSETS_FOLDER)
                ?: assetsRoot.createDirectory(ASSETS_FOLDER)
                ?: error("No se pudo crear $ASSETS_FOLDER")
            bridgeGames.groupBy { it.systemId }.forEach { (systemId, systemGames) ->
                val systemFolder = brandAssets.findFile(systemId)
                    ?: brandAssets.createDirectory(systemId)
                    ?: return@forEach
                systemGames.forEach { game ->
                    val gameFolder = systemFolder.findFile(game.id)
                        ?: systemFolder.createDirectory(game.id)
                        ?: return@forEach
                    if (writeAssetManifest(gameFolder, game)) assetCount++
                    if (writeSelectedArtwork(gameFolder, game, preferences)) artworkCount++
                }
            }
        }

        return ExportResult(descriptorCount, exportedSystems.size, assetCount, artworkCount, missing.distinct().sorted())
    }

    /**
     * Deletes only descriptors generated by Oz from the single global bridge.
     * Real ROM files are never removed because every candidate must pass isGeneratedDescriptor().
     * This is an explicit maintenance action; normal publication is additive.
     */
    fun clearGeneratedBridge(preferences: AppPreferences): Int {
        val global = preferences.globalVirtualTreeUri ?: return 0
        val selectedRoot = DocumentFile.fromTreeUri(context, global) ?: return 0
        val brandRoot = selectedRoot.findFile(BRAND_FOLDER) ?: return 0
        var removed = 0
        brandRoot.listFiles().filter { it.isDirectory }.forEach { platformFolder ->
            platformFolder.listFiles().forEach { candidate ->
                if (isGeneratedDescriptor(candidate) && candidate.delete()) removed++
            }
        }
        return removed
    }

    fun exportIntegrationPack(tree: Uri): IntegrationPackResult {
        val root = DocumentFile.fromTreeUri(context, tree)
            ?: error("Android no pudo abrir la carpeta de exportación.")
        root.findFile(INTEGRATION_PACK_FILE)?.delete()
        val file = root.createFile("application/zip", INTEGRATION_PACK_FILE)
            ?: error("No se pudo crear $INTEGRATION_PACK_FILE")
        context.contentResolver.openOutputStream(file.uri, "w")?.use { output ->
            ZipOutputStream(output).use { zip ->
                zip.putText("README-IIISU.txt", integrationReadme())
                zip.putText("CUSTOM-LAUNCH-COMMAND.txt", IISU_LAUNCH_COMMAND)
                zip.putText("emuladores.template.json", emulatorTemplate().toString(2))
                zip.putText("supported_emulators.template.json", supportedTemplate().toString(2))
                zip.putText("oz-retrorom-bridge.json", bridgeManifest().toString(2))
            }
        } ?: error("No se pudo escribir el pack de integración.")
        return IntegrationPackResult(INTEGRATION_PACK_FILE, IISU_LAUNCH_COMMAND)
    }

    fun export(tree: Uri, games: List<GameEntity>): Int {
        val bridgeGames = games.distinctBy { it.id }
        val root = DocumentFile.fromTreeUri(context, tree) ?: error("Carpeta iiSU no disponible")
        val platformRoot = root.findFile(BRAND_FOLDER) ?: root.createDirectory(BRAND_FOLDER)
            ?: error("No se pudo crear la raíz")
        var count = 0
        bridgeGames.groupBy { it.systemId }.forEach { (systemId, systemGames) ->
            val platform = platformRoot.findFile(systemId) ?: platformRoot.createDirectory(systemId) ?: return@forEach
            systemGames.forEach { if (writeDescriptor(platform, it)) count++ }
        }
        return count
    }

    private fun writeDescriptor(folder: DocumentFile, game: GameEntity): Boolean {
        val extension = game.virtualExtension.ifBlank { "ozr" }
        val name = "${game.id}.$extension"
        folder.findFile(name)?.delete()
        val mime = when (extension.lowercase()) {
            "zip" -> "application/zip"
            "iso" -> "application/x-iso9660-image"
            else -> "application/octet-stream"
        }
        val file = folder.createFile(mime, name) ?: return false
        val descriptor = descriptor(game)
        val output = context.contentResolver.openOutputStream(file.uri, "wt") ?: return false
        if (extension.equals("zip", ignoreCase = true)) {
            ZipOutputStream(output).use { zip ->
                zip.putNextEntry(ZipEntry("oz-retrorom.json"))
                zip.write(descriptor.toString(2).toByteArray(Charsets.UTF_8))
                zip.closeEntry()
            }
        } else {
            output.bufferedWriter().use { it.write(descriptor.toString(2)) }
        }
        return true
    }


    private fun isGeneratedDescriptor(candidate: DocumentFile): Boolean {
        if (!candidate.isFile || candidate.length() !in 1..64_000L) return false

        return runCatching {
            context.contentResolver.openInputStream(candidate.uri)?.use { input ->
                if (candidate.name?.endsWith(".zip", ignoreCase = true) == true) {
                    ZipInputStream(BufferedInputStream(input)).use { zip ->
                        var descriptorFound = false
                        while (true) {
                            val entry = zip.nextEntry ?: break
                            if (entry.name.equals("oz-retrorom.json", ignoreCase = true)) {
                                descriptorFound = true
                                break
                            }
                        }
                        descriptorFound
                    }
                } else {
                    val text = input.bufferedReader().use { it.readText() }
                    text.contains("\"brand\"") &&
                        text.contains("Oz RetroRom") &&
                        text.contains("\"gameId\"")
                }
            } ?: false
        }.getOrDefault(false)
    }

    private fun writeAssetManifest(folder: DocumentFile, game: GameEntity): Boolean {
        val name = "metadata.json"
        folder.findFile(name)?.delete()
        val file = folder.createFile("application/json", name) ?: return false
        val json = descriptor(game)
            .put("thumbnailRepository", game.thumbnailRepo ?: JSONObject.NULL)
            .put("preferredArtwork", JSONArray(listOf("Named_Boxarts", "Named_Titles", "Named_Snaps")))
        context.contentResolver.openOutputStream(file.uri, "wt")?.bufferedWriter()?.use {
            it.write(json.toString(2))
        } ?: return false
        return true
    }


    private fun writeSelectedArtwork(folder: DocumentFile, game: GameEntity, preferences: AppPreferences): Boolean {
        val bitmap = ArtworkResolver.candidates(context, preferences, game)
            .firstNotNullOfOrNull { decodeArtwork(it) }
            ?: return false
        val name = "boxart.png"
        folder.findFile(name)?.delete()
        val file = folder.createFile("image/png", name) ?: return false
        val success = context.contentResolver.openOutputStream(file.uri, "wt")?.use { output ->
            bitmap.compress(Bitmap.CompressFormat.PNG, 100, output)
        } ?: false
        if (!bitmap.isRecycled) bitmap.recycle()
        return success
    }

    private fun decodeArtwork(source: String): Bitmap? = runCatching {
        val uri = Uri.parse(source)
        when (uri.scheme?.lowercase()) {
            "content", "file" -> context.contentResolver.openInputStream(uri)?.use { BitmapFactory.decodeStream(it) }
            "http", "https" -> {
                val connection = URL(source).openConnection() as HttpURLConnection
                connection.connectTimeout = 10_000
                connection.readTimeout = 20_000
                connection.instanceFollowRedirects = true
                connection.setRequestProperty("User-Agent", "OzRetroRom/0.6.0-beta.4")
                try {
                    if (connection.responseCode !in 200..299) null
                    else connection.inputStream.use { BitmapFactory.decodeStream(it) }
                } finally {
                    connection.disconnect()
                }
            }
            else -> null
        }
    }.getOrNull()

    private fun descriptor(game: GameEntity): JSONObject = JSONObject()
        .put("schema", 2)
        .put("gameId", game.id)
        .put("title", game.title)
        .put("platform", game.systemId)
        .put("platformName", game.platform)
        .put("region", game.region)
        .put("genre", game.genre)
        .put("romSet", game.romSet ?: JSONObject.NULL)
        .put("biosSets", JSONArray(game.biosSets))
        .put("core", game.coreId ?: JSONObject.NULL)
        .put("contentMode", "oz-virtual-on-demand")
        .put("brand", "Oz RetroRom")
        .put("launcherPackage", context.packageName)
        .put("launcherActivity", "cl.gakuto.kizuna.launch.SessionActivity")
        .put("launchCommand", IISU_LAUNCH_COMMAND)

    private fun integrationReadme(): String = """
        OZ RETROROM · PUENTE DE JUEGO PARA iiSU
        =======================================

        Objetivo
        - Oz RetroRom administra las ROMs reales, las descargas y la biblioteca SAF.
        - iiSU puede ser tu frontend visual: recibe accesos virtuales, nunca una segunda copia de las ROMs.
        - Un acceso puede representar un juego ya local o uno todavía no descargado.

        Custom Launch Command para iiSU:
        $IISU_LAUNCH_COMMAND

        Configuración inicial (una sola vez)
        1. En Oz: Configuración > Emulación e integraciones > iiSU > Elegir carpeta de puente.
        2. En iiSU: usa la subcarpeta de plataforma generada por Oz (por ejemplo Oz RetroRom/snes)
           como carpeta de ROMs de ESA consola. No añadas también tu carpeta real de ROMs a la misma
           consola o iiSU mostrará duplicados.
        3. En iiSU: Console Settings > Emulator > Custom Launch Command y pega el comando de arriba.
           Las comillas alrededor de %ROM% son obligatorias para rutas que contienen espacios.
        4. En Oz: abre una colección y pulsa "Publicar en iiSU". Las publicaciones son acumulativas.
        5. En iiSU: Summary > Update para volver a indexar la consola.
        6. Al pulsar Jugar, Oz identifica el acceso por su ID incluso si Android no permite abrir la
           ruta raw del descriptor. Si la ROM ya existe la usa; si falta, inicia el flujo normal de descarga.

        Importante
        - Los archivos de puente no contienen ROMs y pueden regenerarse en cualquier momento.
        - La ROM real continúa siendo SAF + Room dentro de Oz RetroRom.
        - Usa SOLO el Bridge como fuente de esa consola en iiSU para evitar duplicados.
        - No habilites hashing de RetroAchievements sobre los descriptores de puente.
        - Si iiSU cambia su esquema de configuración, conserva siempre el Custom Launch Command.
    """.trimIndent()

    private fun emulatorTemplate(): JSONObject = JSONObject().apply {
        put("id", "oz-retrorom")
        put("name", "Oz RetroRom Bridge")
        put("package", context.packageName)
        put("activity", SESSION_ACTIVITY)
        put("extensions", JSONArray(listOf("zip", "sfc", "smc", "gba", "gb", "gbc", "z64", "n64", "chd", "cue", "iso", "3ds", "md", "bin", "rom", "ozr")))
        put("commands", JSONArray().put(JSONObject().apply {
            put("description", "Oz RetroRom · jugar automáticamente")
            put("command", IISU_LAUNCH_COMMAND)
        }))
        put("command", IISU_LAUNCH_COMMAND)
    }

    private fun supportedTemplate(): JSONObject = JSONObject().apply {
        put("id", "oz-retrorom")
        put("name", "Oz RetroRom Bridge")
        put("packageNames", JSONArray(listOf(context.packageName)))
        put("activity", SESSION_ACTIVITY)
        put("command", IISU_LAUNCH_COMMAND)
    }

    private fun bridgeManifest(): JSONObject = JSONObject().apply {
        put("schema", 1)
        put("brand", "Oz RetroRom")
        put("package", context.packageName)
        put("activity", SESSION_ACTIVITY)
        put("launchCommand", IISU_LAUNCH_COMMAND)
        put("romExtra", "ROM")
        put("behavior", "descriptor-or-real-rom-to-authorized-session")
    }

    private fun ZipOutputStream.putText(name: String, text: String) {
        putNextEntry(ZipEntry(name))
        write(text.toByteArray(Charsets.UTF_8))
        closeEntry()
    }

    companion object {
        const val SESSION_ACTIVITY = "cl.gakuto.kizuna.launch.SessionActivity"
        const val IISU_LAUNCH_COMMAND = "cl.gakuto.kizuna/cl.gakuto.kizuna.launch.SessionActivity -a cl.gakuto.kizuna.action.PLAY -e ROM \"%ROM%\" --activity-clear-top"
        private const val INTEGRATION_PACK_FILE = "Oz-RetroRom-iiSU-Integration.zip"
        private const val BRAND_FOLDER = "Oz RetroRom"
        private const val ASSETS_FOLDER = "Oz RetroRom Assets"
    }
}
